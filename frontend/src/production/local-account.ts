import type { CursorAuthStatus } from "../recovered/contracts/desktop-bridge";

/**
 * Локальная учётная запись рендерера — единственный «аккаунт», который есть в
 * DB Bot Lite.
 *
 * Что было. Рендерер спрашивал `account?.kind` больше чем в сорока местах:
 * список помощников, поле ввода, онбординг, черновики, видимость панелей,
 * счётчики. Пока `kind !== "logged-in"`, не показывался ни онбординг, ни поле
 * ввода, а вместо них рисовался экран «Войти в Cursor». Кнопка «Войти» звала
 * `cursorAccount.login()`, который открывал адрес Cursor и падал с
 * `Invalid URL`. Пользователь — заведующая детской библиотеки; аккаунт Cursor
 * ей никто не заводил и просить об этом нельзя.
 *
 * Почему локальный слот, а не правка сорока проверок. `account.kind` в
 * рендерере — это признак «рабочая область доступна», а не
 * «пользователь вошёл в чужую службу». Одна константа даёт всем сорока
 * проверкам одинаковый ответ, и добавление новой проверки не может снова
 * закрыть интерфейс.
 *
 * Почему слот — строка `local`. Рендерер передаёт слот в подсистемы, которые
 * ведут своё состояние по ключу «слот + агент»: черновики, закреплённые
 * помощники, свёрнутые разделы, подтверждения отправки, палитра. Раньше там
 * стоял настоящий идентификатор аккаунта. Постоянная строка даёт то же
 * пространство имён, не выдаёт наружу ни одного адреса и не требует входа.
 *
 * Двойник этого модуля в главном процессе — `source/electron-main/account/
 * local-account.ts`. Слоты должны совпадать: под `local` работает координатор.
 */
export const LOCAL_ACCOUNT_SLOT = "local";

/** Имя, которое программа показывает вместо имени аккаунта. */
export const LOCAL_ACCOUNT_DISPLAY_NAME = "DB Bot";

/** Статус, который рендерер читает как «рабочая область доступна». */
export const LOCAL_ACCOUNT_STATUS: CursorAuthStatus = {
  kind: "logged-in",
  authId: LOCAL_ACCOUNT_SLOT,
  displayName: LOCAL_ACCOUNT_DISPLAY_NAME,
};

/**
 * Статус ответа главного процесса, приведённый к локальной записи.
 *
 * Главный процесс уже отдаёт `logged-in` локальной записи
 * (`asLocalAccountStatus`). Эта функция оставлена как единственное место, где
 * рендерер решает, во что превращается ответ моста: если ответ не дошёл или
 * пришёл с чужим `kind`, интерфейс всё равно получает локальный слот, а не
 * пустой экран входа.
 */
export function toLocalAccountStatus(status: CursorAuthStatus | null | undefined): CursorAuthStatus {
  return status?.kind === "logged-in" ? status : LOCAL_ACCOUNT_STATUS;
}