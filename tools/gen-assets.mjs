/* ================= PNG encoder ================= */

const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const out = Buffer.alloc(12 + data.length);
  out.writeUInt32BE(data.length, 0);
  out.write(type, 4, "ascii");
  data.copy(out, 8);
  out.writeUInt32BE(crc32(out.subarray(4, 8 + data.length)), 8 + data.length);
  return out;
}

/** RGBA (Uint8ClampedArray или Buffer, 4 байта на пиксель) → PNG Buffer */
function encodePng(width, height, rgba) {
  const stride = width * 4;
  const raw = Buffer.alloc((stride + 1) * height);
  for (let y = 0; y < height; y++) {
    raw[y * (stride + 1)] = 0; // фильтр "None"
    Buffer.from(rgba.buffer, y * stride, stride).copy(raw, y * (stride + 1) + 1);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // RGBA
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

/* ================= Крошечный растеризатор =================
 * Координаты — в финальных пикселях; внутри — суперсемплинг SS×SS
 * и стандартное альфа-компонентирование (source-over). */

const SS = 4;

function hexColor(spec, alpha = 255) {
  const h = spec.replace("#", "");
  const r = parseInt(h.slice(0, 2), 16);
  const g = parseInt(h.slice(2, 4), 16);
  const b = parseInt(h.slice(4, 6), 16);
  return { kind: "solid", r, g, b, a: Math.max(0, Math.min(255, Math.round(alpha))) };
}

function linGrad(x1, y1, x2, y2, stops) {
  const cs = stops.map(([t, spec]) => [t, hexColor(spec)]);
  const dx = x2 - x1,
    dy = y2 - y1,
    len2 = dx * dx + dy * dy;
  return {
    kind: "grad",
    at(x, y) {
      const t = len2 ? Math.max(0, Math.min(1, ((x - x1) * dx + (y - y1) * dy) / len2)) : 0;
      let i = 0;
      while (i < cs.length - 1 && cs[i + 1][0] < t) i++;
      const [t0, c0] = cs[i];
      const [t1, c1] = cs[Math.min(i + 1, cs.length - 1)];
      const f = t1 > t0 ? (t - t0) / (t1 - t0) : 0;
      return [
        c0.r + (c1.r - c0.r) * f,
        c0.g + (c1.g - c0.g) * f,
        c0.b + (c1.b - c0.b) * f,
        c0.a + (c1.a - c0.a) * f,
      ];
    },
  };
}

function colorAt(fill, x, y) {
  return fill.kind === "solid" ? [fill.r, fill.g, fill.b, fill.a] : fill.at(x, y);
}

/** Возвращает функцию: расстояние до границы (отриц. внутри) для формы. */
function sdCircle(cx, cy, r) {
  return (x, y) => Math.hypot(x - cx, y - cy) - r;
}
function sdRRect(x0, y0, w, h, r) {
  return (x, y) => {
    const qx = Math.abs(x - (x0 + w / 2)) - (w / 2 - r);
    const qy = Math.abs(y - (y0 + h / 2)) - (h / 2 - r);
    const ox = Math.max(qx, 0),
      oy = Math.max(qy, 0);
    return Math.hypot(ox, oy) + Math.min(Math.max(qx, qy), 0) - r;
  };
}
function sdSeg(px, py, ax, ay, bx, by) {
  const dx = bx - ax,
    dy = by - ay;
  const t = Math.max(0, Math.min(1, len2(dx, dy) ? ((px - ax) * dx + (py - ay) * dy) / len2(dx, dy) : 0));
  return Math.hypot(px - (ax + dx * t), py - (ay + dy * t));
}
function len2(dx, dy) {
  return dx * dx + dy * dy;
}
function inPoly(x, y, pts) {
  let inside = false;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const [xi, yi] = pts[i],
      [xj, yj] = pts[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
/** Многоугольник; expand < 0 рисует "свечение" — дистанцию наружу. */
function sdPoly(pts, expand = 0) {
  return (x, y) => {
    let d = Infinity;
    for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
      d = Math.min(d, sdSeg(x, y, pts[j][0], pts[j][1], pts[i][0], pts[i][1]));
    }
    return (inPoly(x, y, pts) ? -d : d) + expand * -1 * -1; // expand положительный = шире
  };
}

function makeCanvas(w, h) {
  const W = w * SS,
    H = h * SS;
  const px = new Uint8ClampedArray(W * H * 4);

  function drawSdf(bbox, sdf, fill) {
    const x0 = Math.max(0, Math.floor(bbox[0] * SS));
    const y0 = Math.max(0, Math.floor(bbox[1] * SS));
    const x1 = Math.min(W, Math.ceil(bbox[2] * SS));
    const y1 = Math.min(H, Math.ceil(bbox[3] * SS));
    for (let y = y0; y < y1; y++) {
      const fy = (y + 0.5) / SS;
      for (let x = x0; x < x1; x++) {
        const fx = (x + 0.5) / SS;
        const d = sdf(fx, fy);
        const cov = Math.max(0, Math.min(1, 0.5 - d)); // ~1px AA-полоса
        if (cov <= 0) continue;
        const [r, g, b, a] = colorAt(fill, fx, fy);
        const sa = (a / 255) * cov;
        if (sa <= 0) continue;
        const i = (y * W + x) * 4;
        const da = px[i + 3] / 255;
        const oa = sa + da * (1 - sa);
        if (oa <= 0) continue;
        px[i] = (r * sa + px[i] * da * (1 - sa)) / oa;
        px[i + 1] = (g * sa + px[i + 1] * da * (1 - sa)) / oa;
        px[i + 2] = (b * sa + px[i + 2] * da * (1 - sa)) / oa;
        px[i + 3] = oa * 255;
      }
    }
  }

  const api = {
    w,
    h,
    fillAll(fill) {
      drawSdf([0, 0, w, h], () => -1, fill);
    },
    rrect(x, y, rw, rh, r, fill) {
      drawSdf([x, y, x + rw, y + rh], sdRRect(x, y, rw, rh, r), fill);
    },
    circle(cx, cy, r, fill) {
      drawSdf([cx - r, cy - r, cx + r, cy + r], sdCircle(cx, cy, r), fill);
    },
    ring(cx, cy, r, thick, fill) {
      drawSdf(
        [cx - r - thick, cy - r - thick, cx + r + thick, cy + r + thick],
        (x, y) => Math.abs(Math.hypot(x - cx, y - cy) - r) - thick / 2,
        fill
      );
    },
    poly(pts, fill, expand = 0) {
      const xs = pts.map((p) => p[0]),
        ys = pts.map((p) => p[1]);
      const m = Math.max(2, expand + 2);
      drawSdf(
        [Math.min(...xs) - m, Math.min(...ys) - m, Math.max(...xs) + m, Math.max(...ys) + m],
        (x, y) => {
          let d = Infinity;
          for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
            d = Math.min(d, sdSeg(x, y, pts[j][0], pts[j][1], pts[i][0], pts[i][1]));
          }
          return (inPoly(x, y, pts) ? -d : d) - expand;
        },
        fill
      );
    },
    rect(x, y, rw, rh, fill) {
      api.rrect(x, y, rw, rh, 0.01, fill);
    },
    /** Текст пиксельным шрифтом 5×7, scale — целое число. Возвращает ширину. */
    text(str, x, y, scale, fill) {
      let cx = x;
      for (const ch of str) {
        if (ch === " ") {
          cx += 4 * scale;
          continue;
        }
        const g = GLYPHS[ch] || GLYPHS["?"];
        const gw = g[0].length;
        const gh = g.length;
        for (let row = 0; row < gh; row++)
          for (let col = 0; col < gw; col++)
            if (g[row][col] === "#")
              api.rect(cx + col * scale, y + row * scale, scale, scale, fill);
        cx += (gw + 1) * scale;
      }
      return cx - x - scale;
    },
    textW(str, scale) {
      let wpx = 0;
      for (const ch of str) {
        if (ch === " ") {
          wpx += 4 * scale;
          continue;
        }
        wpx += ((GLYPHS[ch] || GLYPHS["?"])[0].length + 1) * scale;
      }
      return Math.max(0, wpx - scale);
    },
    textCenter(str, cx, y, scale, fill) {
      api.text(str, Math.round(cx - api.textW(str, scale) / 2), y, scale, fill);
    },
    /** Сохранение: даунсемпл SS→1 и PNG. */
    save(path) {
      const out = new Uint8ClampedArray(w * h * 4);
      for (let y = 0; y < h; y++)
        for (let x = 0; x < w; x++) {
          let r = 0,
            g = 0,
            b = 0,
            a = 0;
          for (let sy = 0; sy < SS; sy++)
            for (let sx = 0; sx < SS; sx++) {
              const i = ((y * SS + sy) * W + (x * SS + sx)) * 4;
              r += px[i];
              g += px[i + 1];
              b += px[i + 2];
              a += px[i + 3];
            }
          const n = SS * SS,
            o = (y * w + x) * 4;
          out[o] = r / n;
          out[o + 1] = g / n;
          out[o + 2] = b / n;
          out[o + 3] = a / n;
        }
      writeFileSync(path, encodePng(w, h, out));
      console.log("written:", path);
    },
  };
  return api;
}

