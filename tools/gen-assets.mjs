/* Мини-иконки сайдбара (~22px, центр (cx,cy)). */
function drawFolderIcon(cv, cx, cy) {
  const ink = hexColor("#c9bfff");
  cv.rrect(cx - 10, cy - 7, 20, 15, 2.5, ink);
  cv.rect(cx - 10, cy - 9, 8, 4, ink); // «язычок» папки
  cv.rect(cx - 10, cy - 7, 20, 4, ink);
}
function drawChatIcon(cv, cx, cy) {
  const ink = C.textDim;
  cv.rrect(cx - 10, cy - 8, 20, 14, 5, ink);
  cv.poly(
    [
      [cx - 5, cy + 6],
      [cx - 5, cy + 12],
      [cx + 1, cy + 6],
    ],
    ink
  );
  for (const dx of [-5, 0, 5]) cv.rect(cx + dx - 1.5, cy - 3, 3, 3, C.panel); // точки
}
function drawGearIcon(cv, cx, cy) {
  const ink = C.textDim;
  cv.ring(cx, cy, 6, 4, ink);
  for (let i = 0; i < 8; i++) {
    const a = (i / 8) * Math.PI * 2;
    cv.rect(cx + Math.cos(a) * 7.5 - 1.5, cy + Math.sin(a) * 7.5 - 1.5, 3, 3, ink);
  }
}

