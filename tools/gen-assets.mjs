/* Геометрия молнии (центр — (0,0), высота ~700 в масштабе 1024). */
function boltPoints(scale = 1) {
  return [
    [-92, -352],
    [142, -352],
    [8, -70],
    [152, -70],
    [-118, 352],
    [-42, 8],
    [-142, 8],
  ].map(([x, y]) => [x * scale, y * scale]);
}

function drawBolt(canvas, cx, cy, scale) {
  const pts = boltPoints(scale).map(([x, y]) => [x + cx, y + cy]);
  canvas.poly(
    pts,
    linGrad(cx, cy - 360 * scale, cx, cy + 360 * scale, [
      [0, "#ffffff"],
      [1, "#d6c9ff"],
    ])
  );
}

